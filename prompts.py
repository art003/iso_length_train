def user_prompt(sheet_no: int, line_id: str, candidates: list[dict]) -> str:
    lines = [
        f"Лист {sheet_no}, линия {line_id}. Размеры в мм.",
        "На картинке метки D1, D2...",
        "Список:",
    ]
    for c in candidates:
        lines.append(f"- {c['id']}: {c['value_mm']} мм; {c['local_hint']}; рядом: {c['nearby'][:160]}")
    lines.extend(
        [
            "Перед JSON составь решение внутренне по каждому прямому прогону, но рассуждения не печатай.",
            "Контроль LC_1040: 60+1950+650+840+522+250+34=4306; 916 и 300 не брать.",
            "Контроль SW_1001: 23525+1000+24100=48625; неполные цепочки опор не брать.",
        ]
    )
    return "\n".join(lines)


def review_prompt(
    sheet_no: int,
    line_id: str,
    candidates: list[dict],
    first: dict,
    hint: str = "",
) -> str:
    lines = [
        f"Лист {sheet_no}, линия {line_id}. Второй проход, проверь черновик по картинке.",
        "Черновик первого прохода:",
    ]
    for it in first.get("items") or []:
        lines.append(f"- {it.get('id')}: {it.get('decision')} / {it.get('reason') or ''}")
    if hint:
        lines.append("Python уже заметил: " + hint)
    lines.append("Размеры:")
    for c in candidates:
        lines.append(f"- {c['id']}: {c['value_mm']} мм; {c['local_hint']}; рядом: {c['nearby'][:120]}")
    lines.append(
        "Особенно проверь: полный размер против суммы цепочки, потерянный хвост участка и двойной счёт. "
        "Исправь ошибки. Верни полный JSON, все id."
    )
    return "\n".join(lines)
